#!/usr/bin/env python3
"""Publish a MinkNote markdown article as a Jekyll blog post.

Takes a MinkNote-authored article plus its `i/` image folder and produces a
dated, front-matter-complete post inside a Jekyll site's blog section. Images
are optimised and copied to the blog image folder, the MinkNote blog Jekyll
plugin is installed when missing, and `llms.txt` is updated when present.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from urllib.parse import quote, unquote

try:
    from zoneinfo import ZoneInfo
except ImportError:  # pragma: no cover - Python < 3.9
    ZoneInfo = None  # type: ignore[assignment]

FRONT_MATTER_RE = re.compile(r"^---\n(.*?)\n---\n?(.*)\Z", re.S)
H1_RE = re.compile(r"^#\s+(.+?)\s*$", re.M)
IMAGE_RE = re.compile(r"!\[([^\]]*)\]\((i/[^)\s]+)\)")
LEADING_NUM_RE = re.compile(r"^\d+\.\s*")
DRAFT_VERSION_RE = re.compile(r"\s*/v\d+\s*$", re.I)
UNSAFE_FILENAME_RE = re.compile(r"[^A-Za-z0-9._-]+")
YOUTUBE_RE = re.compile(r"\{\{youtube:([A-Za-z0-9_-]+)\}\}")
SIPS_INFO_KEYS = ("pixelWidth", "pixelHeight", "hasAlpha")

PLUGIN_TEMPLATE = """# frozen_string_literal: true

# MinkNote product blog: dated Markdown files in __POSTS_DIR__/
# become pages at __URL_PREFIX__/<slug>/.
#
# Generated by the mink-publish-blog-post agent skill.

module MinknoteBlog
  POSTS_DIR = "__POSTS_DIR__"
  URL_PREFIX = "__URL_PREFIX__"
  FILENAME_PATTERN = %r{\\A#{Regexp.escape(POSTS_DIR)}/(\\d{4}-\\d{2}-\\d{2})-(.+)\\.(md|markdown|html)\\z}

  module Permalink
    def self.apply(page)
      match = FILENAME_PATTERN.match(page.path.delete_prefix("/"))
      return unless match

      date_str, slug = match[1], match[2]
      page.data["date"] ||= Jekyll::Utils.parse_date("#{date_str} 00:00:00")
      page.data["permalink"] ||= "#{URL_PREFIX}/#{slug}/"
      page.data["layout"] ||= "__LAYOUT__"
      page.data["minknote_blog"] = true
      page.data["hero_image"] = page.data["hero-image"] if page.data.key?("hero-image")
      page.data["show_hero"] = page.data["show-hero"] if page.data.key?("show-hero")
    end
  end
end

Jekyll::Hooks.register :pages, :post_init do |page|
  MinknoteBlog::Permalink.apply(page)
end
"""


@dataclass
class Config:
    site_root: Path
    blog_path: Path
    domain: str
    blog_url_prefix: str
    images_url_prefix: str
    layout: str
    llms_section: str
    llms_heading: str
    jpeg_quality: int
    max_width: int
    hero_format: str
    optimise_inline: bool
    inline_threshold_kb: int
    timezone: str
    dry_run: bool
    update_llms: bool


@dataclass
class ImageResult:
    source: Path
    filename: str
    url: str
    optimised: bool = False
    note: str = ""


@dataclass
class PublishResult:
    title: str
    slug: str
    post_path: Path
    post_url: str
    hero: ImageResult | None = None
    images: list[ImageResult] = field(default_factory=list)
    plugin_written: Path | None = None
    plugin_existing: Path | None = None
    llms_updated: bool = False
    warnings: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------- #
# Front matter and text helpers
# --------------------------------------------------------------------------- #

def parse_front_matter(text: str) -> tuple[dict[str, str], str]:
    match = FRONT_MATTER_RE.match(text)
    if not match:
        return {}, text
    meta: dict[str, str] = {}
    for raw_line in match.group(1).splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        meta[key.strip()] = value.strip().strip('"').strip("'")
    return meta, match.group(2).lstrip("\n")


def clean_title(title: str) -> str:
    return DRAFT_VERSION_RE.sub("", title).strip()


def slugify(title: str) -> str:
    slug = LEADING_NUM_RE.sub("", title).lower()
    slug = re.sub(r"[^a-z0-9]+", "-", slug).strip("-")
    return slug or "post"


def sanitise_filename(name: str) -> str:
    stem, dot, suffix = name.rpartition(".")
    if not dot:
        stem, suffix = name, ""
    stem = UNSAFE_FILENAME_RE.sub("-", stem).strip("-") or "image"
    stem = re.sub(r"-{2,}", "-", stem)
    return f"{stem}.{suffix.lower()}" if suffix else stem


def yaml_escape(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def strip_matching_h1(body: str, titles: set[str]) -> str:
    match = H1_RE.search(body)
    if not match:
        return body
    heading = clean_title(match.group(1)).strip()
    wanted = {clean_title(title).strip() for title in titles if title}
    if heading not in wanted:
        return body
    return (body[: match.start()] + body[match.end() :]).lstrip("\n")


def youtube_embed(video_id: str) -> str:
    return (
        '<div class="docs-embed">\n'
        f'  <iframe src="https://www.youtube-nocookie.com/embed/{video_id}" '
        'title="YouTube video" allow="accelerometer; autoplay; clipboard-write; '
        'encrypted-media; gyroscope; picture-in-picture; web-share" '
        'allowfullscreen loading="lazy"></iframe>\n'
        "</div>"
    )


