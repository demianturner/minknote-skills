# Environment helpers
# --------------------------------------------------------------------------- #

def read_site_timezone(site_root: Path) -> str:
    config = site_root / "_config.yml"
    if not config.is_file():
        return "UTC"
    for line in config.read_text(encoding="utf-8").splitlines():
        if line.startswith("timezone:"):
            value = line.split(":", 1)[1].strip().strip('"').strip("'")
            if value:
                return value
    return "UTC"


def resolve_now(timezone: str) -> datetime:
    if ZoneInfo is not None:
        try:
            return datetime.now(ZoneInfo(timezone))
        except Exception:
            pass
    return datetime.now().astimezone()


def sips_available() -> bool:
    return shutil.which("sips") is not None


def sips_info(path: Path) -> dict[str, str]:
    try:
        output = subprocess.run(
            ["sips", "-g", *SIPS_INFO_KEYS, str(path)],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return {}
    info: dict[str, str] = {}
    for line in output.splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            info[key.strip()] = value.strip()
    return info


def image_info(path: Path) -> tuple[int, int, bool]:
    info = sips_info(path)
    try:
        return (
            int(info.get("pixelWidth", "0")),
            int(info.get("pixelHeight", "0")),
            info.get("hasAlpha", "no").lower() == "yes",
        )
    except ValueError:
        return 0, 0, False


def sips_process(src: Path, dest: Path, fmt: str | None, quality: int, max_width: int) -> bool:
    args = ["sips"]
    if max_width and max_width > 0:
        width, _, _ = image_info(src)
        if width > max_width:
            args += ["--resampleWidth", str(max_width)]
    if fmt:
        args += ["-s", "format", fmt]
        if fmt in ("jpeg", "jpg"):
            args += ["-s", "formatOptions", str(quality)]
    args += [str(src), "--out", str(dest)]
    try:
        subprocess.run(args, capture_output=True, text=True, check=True)
        return True
    except (subprocess.CalledProcessError, FileNotFoundError):
        return False


def unique_name(dest_dir: Path, filename: str, claimed: set[str]) -> str:
    if filename not in claimed:
        return filename
    path = Path(filename)
    index = 2
    while f"{path.stem}-{index}{path.suffix}" in claimed:
        index += 1
    return f"{path.stem}-{index}{path.suffix}"


def build_image_url(images_url_prefix: str, filename: str) -> str:
    base = "/" + images_url_prefix.strip("/")
    return f"{base}/{quote(filename)}"


def resolve_source_image(image_dir: Path, link_target: str) -> Path | None:
    """Resolve an `i/<name>` link (percent-encoded) to a file on disk."""
    target = link_target[2:] if link_target.startswith("i/") else link_target
    name = unquote(target)
    candidate = image_dir / name
    if candidate.is_file():
        return candidate
    # Fall back to a case-insensitive / space-tolerant match.
    normalised = name.replace(" ", "-")
    for entry in image_dir.iterdir() if image_dir.is_dir() else []:
        if entry.is_file() and unquote(entry.name) in (name, normalised):
            return entry
    return None


# --------------------------------------------------------------------------- #
# Image publishing
# --------------------------------------------------------------------------- #

def publish_image(
    src: Path,
    images_dir: Path,
    config: Config,
    claimed: set[str],
    *,
    hero: bool,
    out_stem: str,
    rename_map: dict[str, str],
) -> ImageResult:
    width, _, has_alpha = image_info(src)
    suffix = src.suffix.lower()
    size_kb = max(src.stat().st_size // 1024, 1)

    # Decide the output format.
    if hero:
        wanted = config.hero_format
    elif (
        config.optimise_inline
        and suffix == ".png"
        and not has_alpha
        and size_kb >= config.inline_threshold_kb
    ):
        wanted = "jpeg"
    else:
        wanted = "keep"

    if wanted == "keep":
        out_name = unique_name(images_dir, f"{out_stem}{suffix}", claimed)
        converted = False
        note = ""
    else:
        ext = ".jpg" if wanted in ("jpeg", "jpg") else ".png"
        out_name = unique_name(images_dir, f"{out_stem}{ext}", claimed)
        converted = True
        note = ""

    dest = images_dir / out_name

    if converted and not sips_available():
        out_name = unique_name(images_dir, sanitise_filename(src.name), claimed)
        dest = images_dir / out_name
        if not config.dry_run:
            shutil.copy2(src, dest)
        return ImageResult(
            source=src, filename=out_name,
            url=build_image_url(config.images_url_prefix, out_name),
            optimised=False, note="sips unavailable; copied without conversion",
        )

    if config.dry_run:
        note = note or (f"convert to {dest.suffix.lstrip('.')} ({size_kb}KB)" if converted else "")
        return ImageResult(
            source=src, filename=out_name,
            url=build_image_url(config.images_url_prefix, out_name),
            optimised=converted, note=note,
        )

    if converted:
        fmt = "jpeg" if wanted in ("jpeg", "jpg") else "png"
        if sips_process(src, dest, fmt, config.jpeg_quality, config.max_width):
            new_kb = max(dest.stat().st_size // 1024, 1)
            note = f"converted to {dest.suffix.lstrip('.')} ({size_kb}KB to {new_kb}KB)"
            return ImageResult(
                source=src, filename=out_name,
                url=build_image_url(config.images_url_prefix, out_name),
                optimised=True, note=note,
            )
        # Conversion failed; still do not lose the image.
        out_name = unique_name(images_dir, sanitise_filename(src.name), claimed)
        dest = images_dir / out_name
        shutil.copy2(src, dest)
        return ImageResult(
            source=src, filename=out_name,
            url=build_image_url(config.images_url_prefix, out_name),
            optimised=False, note="conversion failed; copied as-is",
        )

    # "keep" format. Optionally downscale very wide images.
    if config.max_width and width > config.max_width and sips_available():
        if sips_process(src, dest, None, config.jpeg_quality, config.max_width):
            return ImageResult(
                source=src, filename=out_name,
                url=build_image_url(config.images_url_prefix, out_name),
                optimised=True, note=f"resized to {config.max_width}px",
            )
    shutil.copy2(src, dest)
    return ImageResult(
        source=src, filename=out_name,
        url=build_image_url(config.images_url_prefix, out_name),
    )


# --------------------------------------------------------------------------- #
# Site integration
# --------------------------------------------------------------------------- #

def ensure_plugin(config: Config, result: PublishResult) -> None:
    plugin_path = config.site_root / "_plugins" / "minknote_blog.rb"
    expected = config.blog_path.as_posix()

    if plugin_path.is_file():
        result.plugin_existing = plugin_path
        text = plugin_path.read_text(encoding="utf-8")
        if f'POSTS_DIR = "{expected}"' not in text:
            result.warnings.append(
                f"{plugin_path} exists but does not target {expected}; left untouched."
            )
        return

    content = (
        PLUGIN_TEMPLATE
        .replace("__POSTS_DIR__", expected)
        .replace("__URL_PREFIX__", config.blog_url_prefix)
        .replace("__LAYOUT__", config.layout)
    )
    if not config.dry_run:
        plugin_path.parent.mkdir(parents=True, exist_ok=True)
        plugin_path.write_text(content, encoding="utf-8")
    result.plugin_written = plugin_path


def update_llms_txt(config: Config, result: PublishResult, description: str) -> bool:
    llms_path = config.site_root / "llms.txt"
    if not llms_path.is_file():
        result.warnings.append("No llms.txt found; skipped.")
        return False

    lines = llms_path.read_text(encoding="utf-8").splitlines()
    bullet = f"- [{result.title}]({result.post_url})"
    if description:
        bullet += f": {description}"

    for index, line in enumerate(lines):
        if f"]({result.post_url})" in line:
            lines[index] = bullet
            break
    else:
        heading = config.llms_heading.lower()
        section_index = next(
            (i for i, line in enumerate(lines) if line.strip().lower() == heading),
            None,
        )
        if section_index is None:
            result.warnings.append(
                f"llms.txt has no '{config.llms_heading}' section; skipped."
            )
            return False

        insert_at = section_index + 1
        for index in range(section_index + 1, len(lines)):
            stripped = lines[index].strip()
            if stripped.startswith("## "):
                break
            if stripped.startswith("- "):
                insert_at = index + 1
        lines.insert(insert_at, bullet)

    if not config.dry_run:
        llms_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return True


# --------------------------------------------------------------------------- #
# Orchestration
# --------------------------------------------------------------------------- #

def parse_rename(values: list[str]) -> dict[str, str]:
    mapping: dict[str, str] = {}
    for value in values or []:
        if "=" not in value:
            raise SystemExit(f"--rename expects SOURCE=DEST, got: {value}")
        source, dest = value.split("=", 1)
        mapping[unquote(source.strip())] = dest.strip()
    return mapping


def publish(args: argparse.Namespace) -> PublishResult:
    article = Path(args.article).expanduser().resolve()
    if not article.is_file():
        raise SystemExit(f"Article not found: {article}")

    site_root = Path(args.site_root).expanduser().resolve()
    if not site_root.is_dir():
        raise SystemExit(f"Site root not found: {site_root}")

    blog_path = Path(args.blog_path)
    blog_dir = site_root / blog_path
    images_dir = blog_dir / "images"

    timezone = args.timezone or read_site_timezone(site_root)
    if args.date:
        date = datetime.strptime(args.date, "%Y-%m-%d").replace(
            tzinfo=resolve_now(timezone).tzinfo
        )
    else:
        date = resolve_now(timezone)

    config = Config(
        site_root=site_root,
        blog_path=blog_path,
        domain=args.domain.rstrip("/"),
        blog_url_prefix="/" + (args.blog_url_prefix or blog_path.as_posix()).strip("/"),
        images_url_prefix=args.images_url_prefix or f"{blog_path.as_posix().strip('/')}/images",
        layout=args.layout,
        llms_section=args.llms_section,
        llms_heading=f"## {args.llms_section}",
        jpeg_quality=args.jpeg_quality,
        max_width=args.max_width,
        hero_format=args.hero_format,
        optimise_inline=args.optimise_inline,
        inline_threshold_kb=args.inline_threshold_kb,
        timezone=timezone,
        dry_run=args.dry_run,
        update_llms=not args.no_llms,
    )

    meta, body = parse_front_matter(article.read_text(encoding="utf-8"))

    title = clean_title(args.title or meta.get("title") or "")
    if not title:
        match = H1_RE.search(body)
        title = clean_title(match.group(1)) if match else ""
    if not title:
        raise SystemExit("Could not determine a title. Pass --title or add one to the article.")

    slug = args.slug or slugify(title)
    description = args.description if args.description is not None else meta.get("description", "")

    image_dir = Path(args.image_dir).expanduser().resolve() if args.image_dir else article.parent / "i"
    rename_map = parse_rename(args.rename)

    first_link = next((m.group(2) for m in IMAGE_RE.finditer(body)), "")
    show_hero = meta.get("show-hero", meta.get("show_hero", "")).lower()
    if args.no_hero or show_hero == "false":
        hero_link = ""
    else:
        hero_link = (
            args.hero_image
            or meta.get("hero-image")
            or meta.get("hero_image")
            or first_link
        )

    result = PublishResult(
        title=title,
        slug=slug,
        post_path=blog_dir / f"{date:%Y-%m-%d}-{slug}.md",
        post_url=f"https://{config.domain}{config.blog_url_prefix}/{slug}/",
    )

    if result.post_path.exists() and not args.force:
        raise SystemExit(f"Post already exists: {result.post_path}\nPass --force to overwrite.")

    if not config.dry_run:
        images_dir.mkdir(parents=True, exist_ok=True)

    claimed: set[str] = set()

    # Hero image: renamed to the post slug for a stable, readable URL.
    if hero_link:
        hero_source = resolve_source_image(image_dir, hero_link)
        if hero_source is None:
            explicit = Path(hero_link)
            if explicit.is_file():
                hero_source = explicit
        if hero_source is None:
            result.warnings.append(f"Hero image not found for link: {hero_link}")
        else:
            hero = publish_image(
                hero_source, images_dir, config, claimed,
                hero=True, out_stem=slug, rename_map=rename_map,
            )
            claimed.add(hero.filename)
            result.hero = hero

    # Inline images.
    link_map: dict[str, str] = {}
    for match in IMAGE_RE.finditer(body):
        link_target = match.group(2)
        if link_target in link_map:
            continue
        source = resolve_source_image(image_dir, link_target)
        if source is None:
            result.warnings.append(f"No file found for image link: {link_target}")
            continue
        if result.hero and source == result.hero.source:
            link_map[link_target] = result.hero.url
            continue
        source_name = unquote(link_target[2:])
        out_stem = rename_map.get(source_name) or Path(sanitise_filename(source_name)).stem
        image = publish_image(
            source, images_dir, config, claimed,
            hero=False, out_stem=out_stem, rename_map=rename_map,
        )
        claimed.add(image.filename)
        link_map[link_target] = image.url
        result.images.append(image)

    # Body: drop the duplicate H1, repoint image links, expand YouTube shortcodes.
    rewritten = strip_matching_h1(body, {title, meta.get("title", "")})
    rewritten = YOUTUBE_RE.sub(lambda m: youtube_embed(m.group(1)), rewritten)

    def replace_image(match: re.Match[str]) -> str:
        alt, target = match.group(1), match.group(2)
        url = link_map.get(target)
        return match.group(0) if url is None else f"![{alt}]({url})"

    rewritten = IMAGE_RE.sub(replace_image, rewritten).rstrip() + "\n"

    front_matter = [
        "---",
        f"layout: {config.layout}",
        f"title: {yaml_escape(title)}",
        f"date: {date:%Y-%m-%d %H:%M %z}",
        f"description: {yaml_escape(description)}" if description else "description:",
    ]
    if result.hero is not None:
        front_matter.append(f"hero-image: {result.hero.filename}")
        front_matter.append("show-hero: true")
    front_matter += ["---", ""]

    if not config.dry_run:
        result.post_path.parent.mkdir(parents=True, exist_ok=True)
        result.post_path.write_text("\n".join(front_matter) + rewritten, encoding="utf-8")

    ensure_plugin(config, result)
    if config.update_llms:
        result.llms_updated = update_llms_txt(config, result, description)

    return result


def relative_path(value: str) -> Path:
    path = Path(value)
    if path.is_absolute():
        raise argparse.ArgumentTypeError("Expected a path relative to --site-root")
    return path


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--article", required=True, help="Path to the MinkNote markdown article.")
    parser.add_argument("--site-root", required=True, help="Path to the Jekyll site root.")
    parser.add_argument("--domain", required=True, help="Public blog domain, e.g. muse23.com.")
    parser.add_argument(
        "--blog-path",
        default="apps/minknote/blog",
        type=relative_path,
        help="Blog section path inside the site.",
    )
    parser.add_argument(
        "--blog-url-prefix",
        default=None,
        help="Public URL prefix for posts. Defaults to /<blog-path>.",
    )
    parser.add_argument(
        "--images-url-prefix",
        default=None,
        help="Public URL prefix for blog images. Defaults to /<blog-path>/images.",
    )
    parser.add_argument("--layout", default="minknote-post", help="Jekyll layout for the post.")
    parser.add_argument("--title", default=None, help="Override the post title.")
    parser.add_argument("--slug", default=None, help="Override the post slug.")
    parser.add_argument("--description", default=None, help="Description for front matter and llms.txt.")
    parser.add_argument("--date", default=None, help="Publish date as YYYY-MM-DD. Defaults to today.")
    parser.add_argument("--timezone", default=None, help="Timezone for the date. Defaults to the site timezone.")
    parser.add_argument("--image-dir", default=None, help="Folder holding the images. Defaults to <article dir>/i.")
    parser.add_argument("--hero-image", default=None, help="Source link or filename for the hero image.")
    parser.add_argument("--no-hero", action="store_true", help="Do not set a hero image.")
    parser.add_argument(
        "--hero-format",
        default="jpeg",
        choices=("jpeg", "png", "keep"),
        help="Output format for the hero image. Defaults to jpeg.",
    )
    parser.add_argument("--jpeg-quality", type=int, default=85, help="JPEG quality for conversions.")
    parser.add_argument("--max-width", type=int, default=0, help="Downscale images wider than this. 0 disables.")
    parser.add_argument(
        "--optimise-inline",
        action="store_true",
        help="Convert large, non-transparent inline PNGs to JPEG.",
    )
    parser.add_argument(
        "--inline-threshold-kb",
        type=int,
        default=800,
        help="Minimum PNG size for --optimise-inline.",
    )
    parser.add_argument(
        "--rename",
        action="append",
        default=[],
        metavar="SOURCE=DEST",
        help="Give an inline image a semantic output name.",
    )
    parser.add_argument("--llms-section", default="MinkNote", help="llms.txt section that lists posts.")
    parser.add_argument("--no-llms", action="store_true", help="Do not update llms.txt.")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing post file.")
    parser.add_argument("--dry-run", action="store_true", help="Report changes without writing files.")
    return parser


def main() -> None:
    args = build_parser().parse_args()
    result = publish(args)

    header = "Dry run" if args.dry_run else "Published"
    print(f"{header}: {result.title}")
    print(f"  post: {result.post_path}")
    print(f"  url:  {result.post_url}")

    if result.hero:
        detail = f" ({result.hero.note})" if result.hero.note else ""
        print(f"  hero: {result.hero.filename}{detail}")
    for image in result.images:
        detail = f" ({image.note})" if image.note else ""
        print(f"  image: {image.filename}{detail}")

    verb = "would write" if args.dry_run else "wrote"
    if result.plugin_written:
        print(f"  plugin: {verb} {result.plugin_written}")
    elif result.plugin_existing:
        print(f"  plugin: already present {result.plugin_existing}")
    if result.llms_updated:
        print(f"  llms.txt: {'would update' if args.dry_run else 'updated'}")

    for warning in result.warnings:
        print(f"  warning: {warning}", file=sys.stderr)


if __name__ == "__main__":
    main()
